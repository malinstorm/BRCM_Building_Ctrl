%5 HENT ELEKTRISITETSPRISER FRA OSLO OMRÅDE/ØSTLANDET 
%% Parametre
area     = "NO1";                      % Oslo / Øst-Norge
baseUrl  = "https://www.hvakosterstrommen.no/api/v1/prices"; % nettadresse
endDate  = datetime(2025,12,10);       % velg sluttdato
startDate = endDate - days(29);        % 30 dager totalt

dates = startDate:endDate; % vektor

allDatetime = datetime.empty(0,1); % tom datetime-kolonne
allPrice    = []; % for lagring

%% Hent priser dag for dag
for d = dates
    url = sprintf('%s/%04d/%02d-%02d_%s.json', baseUrl, year(d), month(d), day(d), area); % string + heltall d formatert med 0 foran + s

    dayData = webread(url); % GET-request rettet mot url          % 

    % JSON har 24 elementer per dag, med feltet NOK_per_kWh 
    dayPrices = [dayData.NOK_per_kWh]; % 1x24 vektor - henter feltet NOK_per_kWh fra API-et

    % Lag tidspunkt 00:00, 01:00, ..., 23:00 for denne dagen d
    dayTimes = d + hours(0:23);
    
    % % Legg dagens tider og priser inn i samlevektorene
    allDatetime = [allDatetime; dayTimes(:)];
    allPrice    = [allPrice; dayPrices(:)];
end

%% Lag tabell klar for Excel - to kolonner
T = table(allDatetime, allPrice,'VariableNames', {'Tidspunkt', 'Pris_NOK_per_kWh'});

%% Skriv til Excel-fil
filename = 'strompriser_30d_NO1.xlsx';
writetable(T, filename);

